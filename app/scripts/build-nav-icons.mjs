// Writes src/nav-icon-art.ts: the places' icons for the sets drawn from
// Phosphor Icons, an open-source family. Run with the folder holding their packages:
//
//   npm install --prefix <dir> @phosphor-icons/core@2.1.1
//   node scripts/build-nav-icons.mjs <dir>/node_modules
//
// Phosphor Icons (MIT, phosphoricons.com). Its licence is kept in the output's header.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const modules = process.argv[2];
if (!modules) throw new Error('Pass the node_modules folder that holds the icon packages.');

const GLYPHS = ['today', 'calendar', 'notes', 'games', 'settings', 'add', 'refresh'];
const NAMES = {
  phosphor: {
    today: 'sun-horizon',
    calendar: 'calendar-dots',
    notes: 'notepad',
    games: 'game-controller',
    settings: 'gear-six',
    add: 'plus',
    refresh: 'arrow-clockwise',
  },
  minimal: {
    today: 'sparkle',
    calendar: 'dots-nine',
    notes: 'text-align-left',
    games: 'joystick',
    settings: 'sliders-horizontal',
    add: 'plus',
    refresh: 'arrow-clockwise',
  },
};

/** The SVG's drawing, without its outer tag, comments or a blank bounding path. */
function inner(file) {
  const text = readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const body = text.slice(text.indexOf('>', text.indexOf('<svg')) + 1, text.lastIndexOf('</svg>'));
  return body
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/g, '')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
}

const phosphor = (weight, names, glyph) =>
  inner(join(modules, '@phosphor-icons/core/assets', weight, `${names[glyph]}-${weight}.svg`));
const each = (draw) => Object.fromEntries(GLYPHS.map((glyph) => [glyph, draw(glyph)]));

// Six sets that differ in kind, not only in weight: the same pictures as
// outlines, as solids, with a colour fill, on coloured tiles; other pictures
// as minimal marks; and pixel art (nav-icons.tsx draws those itself).
const sets = {
  outline: each((glyph) => phosphor('light', NAMES.phosphor, glyph)),
  solid: each((glyph) => phosphor('fill', NAMES.phosphor, glyph)),
  colour: each((glyph) => phosphor('duotone', NAMES.phosphor, glyph)),
  minimal: each((glyph) => phosphor('light', NAMES.minimal, glyph)),
};
const out = `// Generated by app/scripts/build-nav-icons.mjs. Do not edit by hand.
//
// Phosphor Icons 2.1.1, MIT licence, Copyright (c) 2023 Phosphor Icons (phosphoricons.com).
// The full licence texts are in docs/third-party-icons.md.

/** Each set's drawing of each place: SVG markup for the set's own viewBox. */
export const NAV_ICON_ART = ${JSON.stringify(sets, null, 2)} as const;
`;
writeFileSync(new URL('../src/nav-icon-art.ts', import.meta.url), out);
console.log('wrote src/nav-icon-art.ts');
