// Regenerates src/game-logo-art.ts from the round logo artwork in docs/logos.
// Run from the repository root: node app/scripts/build-logo-art.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..');
const source = join(root, 'docs', 'logos');
const target = join(root, 'app', 'src', 'game-logo-art.ts');

/** The outlined name on one face of the coin: every path inside that face's group. */
function face(svg, name, file) {
  const group = svg.match(new RegExp(`<g class="face ${name}">([\\s\\S]*?)</g>`));
  if (!group) throw new Error(`${file}: no "${name}" face`);
  const paths = [...group[1].matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`${file}: the "${name}" face has no outline`);
  return paths.join(' ');
}

const entries = readdirSync(source)
  .filter((file) => file.endsWith('.svg') && file !== 'contact-sheet.svg')
  .sort()
  .map((file) => {
    const svg = readFileSync(join(source, file), 'utf8');
    return [file.replace(/\.svg$/, ''), { front: face(svg, 'front', file), back: face(svg, 'back', file) }];
  });

const body = entries
  .map(([key, art]) => `  ${key}: {\n    front: '${art.front}',\n    back: '${art.back}',\n  },`)
  .join('\n');

writeFileSync(
  target,
  `// Generated by app/scripts/build-logo-art.mjs from docs/logos. Do not edit by hand.

/**
 * The outlined names from each preset game's round logo, in its 1024×1024 box:
 * the full name on the front of the coin, the short name on the back.
 */
export const LOGO_ART: Record<string, { front: string; back: string }> = {
${body}
};
`,
);
console.log(`${entries.length} logos -> ${target}`);
