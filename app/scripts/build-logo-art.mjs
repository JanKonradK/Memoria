// Regenerates src/game-logo-art.ts from the round logo artwork in docs/logos.
// Run from the repository root: node app/scripts/build-logo-art.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..', '..');
const source = join(root, 'docs', 'logos');
const target = join(root, 'app', 'src', 'game-logo-art.ts');

/** The outlined name on one face of the coin: every path inside that face's group. */
function face(svg, name, file) {
  const group = svg.match(new RegExp(`<g class="face ${name}">([\\s\\S]*?)</g>`));
  if (!group) throw new Error(`${file}: no "${name}" face`);
  const paths = [...group[1].matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`${file}: the "${name}" face has no outline`);
  return paths.join(' ');
}

/**
 * A square box centred on a face's outline, with a margin, so a small coin can
 * show its short name filling the coin instead of at the size it has on a large
 * one. The outlines use absolute coordinates, so every number pair is a point
 * on or inside the shape's hull.
 */
function fitBox(d) {
  const numbers = d.match(/-?\d*\.?\d+/g).map(Number);
  let [minX, minY, maxX, maxY] = [Infinity, Infinity, -Infinity, -Infinity];
  for (let index = 0; index + 1 < numbers.length; index += 2) {
    minX = Math.min(minX, numbers[index]);
    maxX = Math.max(maxX, numbers[index]);
    minY = Math.min(minY, numbers[index + 1]);
    maxY = Math.max(maxY, numbers[index + 1]);
  }
  // The longer side sets the size, with room to clear the coin's round edge.
  const side = Math.min(792, Math.max(maxX - minX, maxY - minY) * 1.12);
  const x = (minX + maxX) / 2 - side / 2;
  const y = (minY + maxY) / 2 - side / 2;
  return [x, y, side, side].map((value) => value.toFixed(1)).join(' ');
}

const entries = readdirSync(source)
  .filter((file) => file.endsWith('.svg') && file !== 'contact-sheet.svg')
  .sort()
  .map((file) => {
    const svg = readFileSync(join(source, file), 'utf8');
    const back = face(svg, 'back', file);
    return [file.replace(/\.svg$/, ''), { front: face(svg, 'front', file), back, backBox: fitBox(back) }];
  });

const fronts = join(root, 'app', 'src', 'game-logo-fronts.ts');

const backs = entries
  .map(([key, art]) => `  ${key}: {\n    back: '${art.back}',\n    backBox: '${art.backBox}',\n  },`)
  .join('\n');
writeFileSync(
  target,
  `// Generated by app/scripts/build-logo-art.mjs from docs/logos. Do not edit by hand.

/**
 * The short names from each preset game's round logo, outlined in its 1024×1024
 * box: the back of the coin, and the whole face of a small one (zoomed to
 * \`backBox\` so the name fills it). The full names are game-logo-fronts.ts,
 * loaded only when a coin is drawn large enough to show one.
 */
export const LOGO_ART: Record<string, { back: string; backBox: string }> = {
${backs}
};
`,
);

const frontBody = entries.map(([key, art]) => `  ${key}: '${art.front}',`).join('\n');
writeFileSync(
  fronts,
  `// Generated by app/scripts/build-logo-art.mjs from docs/logos. Do not edit by hand.

/** The full names from each preset game's round logo, outlined in its 1024×1024 box: the front of a large coin. */
export const LOGO_FRONTS: Record<string, string> = {
${frontBody}
};
`,
);
console.log(`${entries.length} logos -> ${target}, ${fronts}`);
